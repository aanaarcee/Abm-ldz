/*
  Base de datos de Registros de Oficina · versión PostgreSQL
  ----------------------------------------------------------
  Es la misma estructura de sql/OficinaRegistros.sql (SQL Server), con los mismos nombres de tablas y columnas.
  PostgreSQL pasa a minúscula los nombres sin comillas, pero el código C# no se entera: el lector de datos
  busca las columnas sin distinguir mayúsculas.

  Equivalencias con SQL Server:
  - INT IDENTITY                 -> INT GENERATED BY DEFAULT AS IDENTITY
  - BIT                          -> BOOLEAN
  - TINYINT                      -> SMALLINT
  - NVARCHAR                     -> VARCHAR (PostgreSQL ya es Unicode)
  - VARBINARY                    -> BYTEA
  - DATETIME2(0) / SYSDATETIME() -> TIMESTAMP(0) / LOCALTIMESTAMP(0)
  - Modern_Spanish_CI_AI         -> colación ci_ai (ICU, sin mayúsculas ni acentos) en los nombres que se comparan por
                                    igualdad o son únicos (usuario, sector, rol, repartición, juzgado). La búsqueda
                                    general usa unaccent + ILIKE.
  - procedimiento sp_BuscarGeneral -> función sp_BuscarGeneral (se invoca con SELECT * FROM sp_BuscarGeneral(...))

  Los lotes se separan con una línea "GO", igual que en el script de SQL Server: la aplicación los ejecuta de a uno.
*/

CREATE EXTENSION IF NOT EXISTS unaccent;
GO
-- Igual que Modern_Spanish_CI_AI: "Pérez" = "perez"
CREATE COLLATION IF NOT EXISTS ci_ai (provider = icu, locale = 'es-u-ks-level1', deterministic = false);
GO

/* ---------- Organización ---------- */

CREATE TABLE Sector (
    IdSector        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nombre          VARCHAR(60)   COLLATE ci_ai NOT NULL CONSTRAINT UQ_Sector_Nombre UNIQUE,
    Clave           VARCHAR(4)    COLLATE ci_ai NOT NULL CONSTRAINT UQ_Sector_Clave UNIQUE,
    -- Qué tipo de filas lleva el sector: 0 Consulta (no carga), 1 Movimientos de actas, 2 Reclamos, 3 Lotes
    Tipo            SMALLINT      NOT NULL CONSTRAINT CK_Sector_Tipo CHECK (Tipo BETWEEN 0 AND 3)
);

CREATE TABLE Rol (
    IdRol           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nombre          VARCHAR(60)   COLLATE ci_ai NOT NULL CONSTRAINT UQ_Rol_Nombre UNIQUE,
    IdSectorPropio  INT           NULL REFERENCES Sector(IdSector),
    EsAdministrador BOOLEAN       NOT NULL DEFAULT false,
    -- El Administrador es una cuenta aparte: un rol de sector nunca puede serlo
    CONSTRAINT CK_Rol_AdminSinSector CHECK (NOT EsAdministrador OR IdSectorPropio IS NULL)
);

-- Una cuenta general por sector. La clave se guarda como hash PBKDF2 con sal.
CREATE TABLE Usuario (
    IdUsuario       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NombreUsuario   VARCHAR(30)   COLLATE ci_ai NOT NULL CONSTRAINT UQ_Usuario_Nombre UNIQUE,
    ClaveHash       BYTEA         NOT NULL,
    ClaveSal        BYTEA         NOT NULL,
    IdRol           INT           NOT NULL REFERENCES Rol(IdRol),
    Activo          BOOLEAN       NOT NULL DEFAULT true
);

-- Qué puede hacer cada rol en cada sector. El Administrador no necesita filas: puede todo.
CREATE TABLE Permiso (
    IdRol           INT NOT NULL REFERENCES Rol(IdRol) ON DELETE CASCADE,
    IdSector        INT NOT NULL REFERENCES Sector(IdSector),
    PuedeLeer       BOOLEAN NOT NULL DEFAULT false,
    PuedeCargar     BOOLEAN NOT NULL DEFAULT false,
    PuedeModificar  BOOLEAN NOT NULL DEFAULT false,
    PuedeEliminar   BOOLEAN NOT NULL DEFAULT false,
    CONSTRAINT PK_Permiso PRIMARY KEY (IdRol, IdSector)
);

/* ---------- Listas fijas ---------- */

-- La repartición es el tipo de acta: el número es el que usa la oficina (62, 58, 25, 1…)
CREATE TABLE Reparticion (
    IdReparticion   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Codigo          SMALLINT     NOT NULL CONSTRAINT UQ_Reparticion_Codigo UNIQUE,
    Nombre          VARCHAR(80)  COLLATE ci_ai NOT NULL CONSTRAINT UQ_Reparticion UNIQUE
);

CREATE TABLE Juzgado (
    IdJuzgado       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nombre          VARCHAR(80)  COLLATE ci_ai NOT NULL CONSTRAINT UQ_Juzgado UNIQUE
);

/* ---------- Personas ---------- */

CREATE TABLE Persona (
    IdPersona       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Apellido        VARCHAR(80)   NOT NULL,   -- o razón social
    Nombre          VARCHAR(80)   NULL,
    TipoDocumento   VARCHAR(4)    NOT NULL DEFAULT 'DNI' CONSTRAINT CK_Persona_TipoDoc CHECK (TipoDocumento IN ('DNI','CUIT')),
    NroDocumento    VARCHAR(13)   NULL        -- solo números; puede faltar
);
CREATE UNIQUE INDEX UQ_Persona_Documento ON Persona(TipoDocumento, NroDocumento) WHERE NroDocumento IS NOT NULL;
CREATE INDEX IX_Persona_Apellido ON Persona(Apellido);

/* ---------- Actas ---------- */

CREATE TABLE Acta (
    IdActa          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NroCausa        VARCHAR(20)   NOT NULL,
    IdReparticion   INT           NOT NULL REFERENCES Reparticion(IdReparticion),
    Anio            SMALLINT      NOT NULL,
    NroActa         VARCHAR(20)   NOT NULL,
    IdJuzgado       INT           NULL REFERENCES Juzgado(IdJuzgado),
    IdPersona       INT           NULL REFERENCES Persona(IdPersona),
    Dominio         VARCHAR(10)   NULL,       -- patente del vehículo, sin espacios ni guiones
    FechaActa       DATE          NOT NULL,
    SumaReclamada   DECIMAL(12,2) NULL,       -- lo que se intima a pagar (también "monto de sentencia")
    GastosAdministrativos DECIMAL(12,2) NULL, -- lo que se agrega a cada infracción
    Observaciones   VARCHAR(500)  NULL,
    Version         INT           NOT NULL DEFAULT 1,
    Eliminado       BOOLEAN       NOT NULL DEFAULT false,
    IdUsuarioAlta   INT           NOT NULL REFERENCES Usuario(IdUsuario),
    FechaAlta       TIMESTAMP(0)  NOT NULL DEFAULT LOCALTIMESTAMP(0),
    IdUsuarioModif  INT           NULL REFERENCES Usuario(IdUsuario),
    FechaModif      TIMESTAMP(0)  NULL,
    -- Lo que hace única a un acta, según la oficina
    CONSTRAINT UQ_Acta_Clave UNIQUE (NroCausa, IdReparticion, Anio)
);
CREATE INDEX IX_Acta_NroActa ON Acta(NroActa);
CREATE INDEX IX_Acta_Persona ON Acta(IdPersona);
CREATE INDEX IX_Acta_Dominio ON Acta(Dominio) WHERE Dominio IS NOT NULL;

-- Copia de cada versión del acta. La versión 1 es el acta original.
CREATE TABLE ActaVersion (
    IdActaVersion   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    IdActa          INT           NOT NULL REFERENCES Acta(IdActa),
    NroVersion      INT           NOT NULL,
    NroActa         VARCHAR(20)   NOT NULL,
    IdJuzgado       INT           NULL,
    IdPersona       INT           NULL,
    Dominio         VARCHAR(10)   NULL,
    FechaActa       DATE          NOT NULL,
    SumaReclamada   DECIMAL(12,2) NULL,
    GastosAdministrativos DECIMAL(12,2) NULL,
    Observaciones   VARCHAR(500)  NULL,
    Motivo          VARCHAR(200)  NULL,
    IdUsuario       INT           NOT NULL REFERENCES Usuario(IdUsuario),
    Fecha           TIMESTAMP(0)  NOT NULL DEFAULT LOCALTIMESTAMP(0),
    CONSTRAINT UQ_ActaVersion UNIQUE (IdActa, NroVersion)
);

-- Lo que cada sector anota sobre un acta (hoy, una fila en su planilla).
CREATE TABLE Movimiento (
    IdMovimiento    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    IdActa          INT           NOT NULL REFERENCES Acta(IdActa),
    IdSector        INT           NOT NULL REFERENCES Sector(IdSector),
    Fecha           DATE          NOT NULL,
    Detalle         VARCHAR(100)  NOT NULL,   -- texto libre hasta tener la lista de movimientos
    Remito          VARCHAR(30)   NULL,
    Observaciones   VARCHAR(500)  NULL,
    Eliminado       BOOLEAN       NOT NULL DEFAULT false,
    IdUsuarioAlta   INT           NOT NULL REFERENCES Usuario(IdUsuario),
    FechaAlta       TIMESTAMP(0)  NOT NULL DEFAULT LOCALTIMESTAMP(0),
    IdUsuarioModif  INT           NULL REFERENCES Usuario(IdUsuario),
    FechaModif      TIMESTAMP(0)  NULL
);
CREATE INDEX IX_Movimiento_Sector ON Movimiento(IdSector) WHERE NOT Eliminado;
CREATE INDEX IX_Movimiento_Acta ON Movimiento(IdActa);
CREATE INDEX IX_Movimiento_Remito ON Movimiento(Remito) WHERE Remito IS NOT NULL;

/* ---------- Lotes y reclamos ---------- */

CREATE TABLE Lote (
    IdLote          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NroLote         VARCHAR(20)   NOT NULL CONSTRAINT UQ_Lote UNIQUE,
    Fecha           DATE          NOT NULL,
    CantTransito    INT           NOT NULL DEFAULT 0,
    CantCompetencia INT           NOT NULL DEFAULT 0,
    CantPrescriptas INT           NOT NULL DEFAULT 0,
    Observaciones   VARCHAR(500)  NULL,
    Eliminado       BOOLEAN       NOT NULL DEFAULT false,
    IdUsuarioAlta   INT           NOT NULL REFERENCES Usuario(IdUsuario),
    FechaAlta       TIMESTAMP(0)  NOT NULL DEFAULT LOCALTIMESTAMP(0),
    IdUsuarioModif  INT           NULL REFERENCES Usuario(IdUsuario),
    FechaModif      TIMESTAMP(0)  NULL
);

-- Avisos de autos abandonados en la vía pública. La oficina lleva el mismo caso en dos planillas
-- (una compartida con Tránsito y otra propia); acá es una sola fila con todos los datos.
CREATE TABLE Reclamo (
    IdReclamo         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NroCaso           VARCHAR(20)   NOT NULL CONSTRAINT UQ_Reclamo UNIQUE,
    Fecha             DATE          NOT NULL, -- fecha de ingreso
    -- Por dónde entró: 1 Tránsito (grúa, chatarra, choques), 2 Gestión de reclamos (vecino por la página del municipio)
    Origen            SMALLINT      NULL CONSTRAINT CK_Reclamo_Origen CHECK (Origen IN (1, 2)),
    -- 1 En abordaje, 2 Verificando, 3 Solucionado
    Estado            SMALLINT      NOT NULL CONSTRAINT DF_Reclamo_Estado DEFAULT 1 CONSTRAINT CK_Reclamo_Estado CHECK (Estado BETWEEN 1 AND 3),
    Ubicacion         VARCHAR(150)  NOT NULL, -- dirección del lugar
    Entrecalles       VARCHAR(150)  NULL,
    Delegacion        VARCHAR(80)   NULL,     -- la delegación que interviene
    Vehiculo          VARCHAR(100)  NULL,     -- marca, color, patente si se sabe
    Denunciante       VARCHAR(120)  NULL,     -- quién avisó y cómo contactarlo; puede ser anónimo
    Verificado        BOOLEAN       NOT NULL DEFAULT false,
    FechaVerificacion DATE          NULL,     -- primera verificación: desde ahí corre el plazo legal
    VerificadoPor     VARCHAR(80)   NULL,     -- inspector que fue
    NroActaInfraccion VARCHAR(20)   NULL,
    FechaNotificacion DATE          NULL,     -- cédula de notificación: último aviso antes de la grúa
    Observaciones     VARCHAR(500)  NULL,
    Eliminado         BOOLEAN       NOT NULL DEFAULT false,
    IdUsuarioAlta     INT           NOT NULL REFERENCES Usuario(IdUsuario),
    FechaAlta         TIMESTAMP(0)  NOT NULL DEFAULT LOCALTIMESTAMP(0),
    IdUsuarioModif    INT           NULL REFERENCES Usuario(IdUsuario),
    FechaModif        TIMESTAMP(0)  NULL
);

/* ---------- Historial de cambios ---------- */

CREATE TABLE Historial (
    IdHistorial     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Entidad         VARCHAR(20)   NOT NULL,   -- Acta, Movimiento, Reclamo, Lote, Permiso…
    IdEntidad       INT           NOT NULL,
    IdSector        INT           NULL REFERENCES Sector(IdSector),
    Accion          VARCHAR(15)   NOT NULL,   -- Alta, Modificación, Baja
    Detalle         VARCHAR(400)  NULL,
    IdUsuario       INT           NOT NULL REFERENCES Usuario(IdUsuario),
    Fecha           TIMESTAMP(0)  NOT NULL DEFAULT LOCALTIMESTAMP(0)
);
CREATE INDEX IX_Historial_Entidad ON Historial(Entidad, IdEntidad);
CREATE INDEX IX_Historial_Fecha ON Historial(Fecha DESC);
GO

/* ---------- Búsqueda general ----------
   Busca en actas (causa, acta, repartición o su número, dominio, persona, documento, observaciones), en lo que
   anotó cada sector (movimiento, remito), en reclamos y en lotes. Solo devuelve filas de los sectores que se le pasan
   (los que el rol puede leer). Con p_idsector busca dentro de un solo sector.
   Ignora mayúsculas y acentos (unaccent + ILIKE). f_coincide() es el "LIKE" de esta búsqueda.
*/
CREATE OR REPLACE FUNCTION f_coincide(p_valor text, p_patron text) RETURNS boolean
LANGUAGE sql STABLE AS $$
    SELECT unaccent(p_valor COLLATE "default") ILIKE unaccent(p_patron COLLATE "default")
$$;
GO

CREATE OR REPLACE FUNCTION sp_BuscarGeneral(p_texto text, p_sectores text, p_idsector int DEFAULT NULL)
RETURNS TABLE (Tipo text, IdSector int, Sector text, Id int, IdActa int, Titulo text, Detalle text, Fecha timestamp)
LANGUAGE sql STABLE AS $$
    WITH ids AS (
        SELECT DISTINCT CASE WHEN trim(v) ~ '^[0-9]{1,9}$' THEN trim(v)::int END AS idsector
        FROM unnest(string_to_array(p_sectores, ',')) AS v
    ),
    s AS (
        SELECT idsector FROM ids WHERE idsector IS NOT NULL AND (p_idsector IS NULL OR idsector = p_idsector)
    ),
    t AS (SELECT '%' || p_texto || '%' AS patron)
    SELECT * FROM (
        -- Actas, una fila por cada sector donde el acta tiene movimientos
        SELECT 'Acta'::text AS Tipo, sc.IdSector, sc.Nombre::text AS Sector, m.IdMovimiento AS Id, a.IdActa,
               CONCAT('Causa ', a.NroCausa, ' · ', r.Codigo, ' · ', r.Nombre, ' · ', a.Anio) AS Titulo,
               CONCAT('Acta ', a.NroActa, COALESCE(' · ' || p.Apellido || COALESCE(', ' || p.Nombre, ''), ''), COALESCE(' · Dominio ' || a.Dominio, ''),
                      ' · ', m.Detalle, COALESCE(' · Remito ' || m.Remito, '')) AS Detalle,
               m.Fecha::timestamp AS Fecha
        FROM Movimiento m
        JOIN s             ON s.IdSector = m.IdSector
        JOIN Sector sc     ON sc.IdSector = m.IdSector
        JOIN Acta a        ON a.IdActa = m.IdActa
        JOIN Reparticion r ON r.IdReparticion = a.IdReparticion
        LEFT JOIN Persona p ON p.IdPersona = a.IdPersona
        CROSS JOIN t
        WHERE NOT m.Eliminado AND NOT a.Eliminado
          AND (f_coincide(a.NroCausa, t.patron) OR f_coincide(a.NroActa, t.patron) OR f_coincide(r.Nombre, t.patron)
               OR a.Anio::text = p_texto OR r.Codigo::text = p_texto OR f_coincide(a.Dominio, t.patron)
               OR f_coincide(p.Apellido, t.patron) OR f_coincide(p.Nombre, t.patron) OR f_coincide(p.NroDocumento, t.patron)
               OR f_coincide(a.Observaciones, t.patron) OR f_coincide(m.Detalle, t.patron) OR f_coincide(m.Remito, t.patron)
               OR f_coincide(m.Observaciones, t.patron))

        UNION ALL
        SELECT 'Reclamo', sc.IdSector, sc.Nombre::text, rc.IdReclamo, NULL::int,
               CONCAT('Caso ', rc.NroCaso),
               CONCAT(rc.Ubicacion, COALESCE(' · ' || rc.Delegacion, ''), COALESCE(' · ' || rc.Vehiculo, ''),
                      CASE rc.Estado WHEN 1 THEN ' · En abordaje' WHEN 2 THEN ' · Verificando' ELSE ' · Solucionado' END),
               rc.Fecha::timestamp
        FROM Reclamo rc
        JOIN Sector sc ON sc.Tipo = 2
        JOIN s         ON s.IdSector = sc.IdSector
        CROSS JOIN t
        WHERE NOT rc.Eliminado
          AND (f_coincide(rc.NroCaso, t.patron) OR f_coincide(rc.Ubicacion, t.patron) OR f_coincide(rc.Entrecalles, t.patron)
               OR f_coincide(rc.Delegacion, t.patron) OR f_coincide(rc.Vehiculo, t.patron) OR f_coincide(rc.Denunciante, t.patron)
               OR f_coincide(rc.VerificadoPor, t.patron) OR f_coincide(rc.NroActaInfraccion, t.patron) OR f_coincide(rc.Observaciones, t.patron))

        UNION ALL
        SELECT 'Lote', sc.IdSector, sc.Nombre::text, l.IdLote, NULL::int,
               CONCAT('Lote ', l.NroLote),
               CONCAT('Tránsito ', l.CantTransito, ' · Competencia ', l.CantCompetencia, ' · Prescriptas ', l.CantPrescriptas),
               l.Fecha::timestamp
        FROM Lote l
        JOIN Sector sc ON sc.Tipo = 3
        JOIN s         ON s.IdSector = sc.IdSector
        CROSS JOIN t
        WHERE NOT l.Eliminado
          AND (f_coincide(l.NroLote, t.patron) OR f_coincide(l.Observaciones, t.patron))
    ) x
    ORDER BY x.Fecha DESC
    LIMIT 300
$$;
GO
